"""
Optiqo — Run Storage & Export Schemas (PRD §5.1 P0-11, §6.7, Plan §4.8, §4.9)
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Literal, Optional
from pydantic import BaseModel, Field


ExportArtifactType = Literal["plan", "risks", "kpis"]
ExportFormat = Literal["csv", "json"]


class RunManifest(BaseModel):
    """
    Immutable manifest persisted for every planning and backtesting run.
    Provides complete reproducibility and audit trail (PRD §6.7, §14 N7).
    """

    run_id: str = Field(description="Unique run identifier (e.g. run_YYYYMMDD_xxxxxxxx).")
    run_type: Literal["PLAN", "BACKTEST"] = Field(
        default="PLAN", description="Type of run execution."
    )
    created_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="UTC ISO-8601 creation timestamp.",
    )
    dataset_hash: str = Field(
        description="SHA-256 fingerprint of the input dataset files."
    )
    origin_date: Optional[str] = Field(
        default=None, description="ISO-8601 planning date (YYYY-MM-DD)."
    )
    seed: Optional[int] = Field(
        default=42, description="Random seed used for generation and reproducibility."
    )
    parameters: dict[str, Any] = Field(
        default_factory=dict, description="Snapshot of execution and cost parameters."
    )
    software_versions: dict[str, str] = Field(
        default_factory=dict, description="Version snapshot of optiqo, python, pulp, lightgbm."
    )
    status: str = Field(
        default="OK", description="Execution status ('OK', 'UNVERIFIED', 'COMPLETED', etc.)."
    )
    solver_status: Optional[str] = Field(
        default=None, description="LP solver status ('OPTIMAL', 'TIME_LIMITED_FEASIBLE', etc.)."
    )
    solver_runtime_seconds: Optional[float] = Field(
        default=None, description="Time taken by the optimization solver."
    )
    checker_verdict: Optional[dict[str, Any]] = Field(
        default=None, description="Independent verification results for hard constraints C1–C5."
    )
    summary: Optional[dict[str, Any]] = Field(
        default=None, description="Summary business and optimization metrics."
    )
    plan_lines: Optional[list[dict[str, Any]]] = Field(
        default=None, description="Planned shipment lines with explanations."
    )
    kpi_comparison: Optional[dict[str, Any]] = Field(
        default=None, description="Comparative KPIs across B1, B2, and Optiqo (backtest runs)."
    )
    available_artifacts: list[str] = Field(
        default_factory=lambda: ["plan", "risks", "kpis"],
        description="List of exportable artifacts generated by this run.",
    )
